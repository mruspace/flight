#!/bin/sh
# Run the quorum demo on the bench schedules and write its counts as the
# expected values of the F´ parity test (MRU-SYS-001):
#   fprime/Mru/Test/Parity/ParityCases.hpp
# With --check, compare instead of writing: fails if the file is out of date.
set -eu
cd "$(dirname "$0")/.."
cargo build --release --quiet -p demo
Q=target/release/quorum
T=4000
out=fprime/Mru/Test/Parity/ParityCases.hpp
tmp=$(mktemp)

field() { printf '%s\n' "$2" | tr ' ' '\n' | sed -n "s/^$1=//p" | head -n 1; }

# the bench's schedules (scripts/bench.sh), at T ticks
faults() {
    case "$1" in
        none) echo "" ;;
        staggered-kills) echo "kill:0@$((T / 4)) kill:1@$((T / 2))" ;;
        common-mode) echo "kill:0@$((T / 10)) kill:1@$((T / 5))" ;;
        stuck) echo "stuck:1@$((T / 5)) kill:0@$((T * 9 / 20))" ;;
        last-stuck) echo "kill:0@$((T / 4)) kill:1@$((T / 2)) stuck:2@$((T * 3 / 4))" ;;
    esac
}

{
    echo "// Generated by scripts/parity-cases.sh from the quorum demo. Do not edit."
    echo "// Each case: the demo's counts for the same schedule, seed and upset rate."
    echo "#ifndef Mru_ParityCases_HPP"
    echo "#define Mru_ParityCases_HPP"
    echo
    echo "#include \"Mru/Test/Parity/ParityCase.hpp\""
    echo
    echo "namespace Mru {"
    echo
    echo "const ParityCase PARITY_CASES[] = {"
    for s in none staggered-kills common-mode stuck last-stuck; do
        f=$(faults "$s")
        opts=""
        list=""
        n=0
        kills=0
        for x in $f; do
            opts="$opts --fault $x"
            kind=$(echo "$x" | cut -d: -f1 | tr '[:lower:]' '[:upper:]')
            rest=${x#*:}
            list="$list{FaultKind::$kind, ${rest%@*}, ${rest#*@}}, "
            n=$((n + 1))
            [ "$kind" = KILL ] && kills=$((kills + 1))
        done
        while [ "$n" -lt 3 ]; do list="$list{FaultKind::KILL, 0, 0}, "; n=$((n + 1)); done
        nf=$(echo "$f" | wc -w | tr -d ' ')
        for r in 0.0001 0.001 0.01; do
            for seed in 1 2; do
                for p in tmr shrink; do
                    # shellcheck disable=SC2086 # opts is a list of options
                    o=$("$Q" --policy "$p" --ticks "$T" --seed "$seed" --upset-rate "$r" $opts | sed -n 2p)
                    P=$(echo "$p" | tr '[:lower:]' '[:upper:]')
                    printf '    {"%s", Policy::%s, %s, %s, %s, %s, %s, {%s}, %s, %s, %s},\n' \
                        "$s" "$P" "$seed" "$r" "$T" "$kills" "$nf" "${list%, }" \
                        "$(field useful "$o")" "$(field detected "$o")" "$(field wrong "$o")"
                done
            done
        done
    done
    echo "};"
    echo
    echo "}  // namespace Mru"
    echo
    echo "#endif"
} >"$tmp"

if [ "${1:-}" = --check ]; then
    if cmp -s "$tmp" "$out"; then
        echo "$out matches the demo"
        rm -f "$tmp"
    else
        diff "$out" "$tmp" | head -20
        rm -f "$tmp"
        echo "$out is out of date: run scripts/parity-cases.sh" >&2
        exit 1
    fi
else
    mv "$tmp" "$out"
    echo "wrote $out"
fi
